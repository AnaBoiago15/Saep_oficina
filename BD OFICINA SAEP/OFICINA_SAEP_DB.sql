CREATE DATABASE IF NOT EXISTS OFICINA_SAEP_DB ;
USE OFICINA_SAEP_DB;

CREATE TABLE IF NOT EXISTS USUARIOS(
	USU_ID INT AUTO_INCREMENT PRIMARY KEY,
    USU_NOME VARCHAR(100) NOT NULL,
    USU_EMAIL VARCHAR(100) NOT NULL,
    USU_SENHA VARCHAR(100) NOT NULL
);


CREATE TABLE IF NOT EXISTS CLIENTES(
	CLI_ID INT AUTO_INCREMENT PRIMARY KEY,
	CLI_NOME VARCHAR(100) NOT NULL,
    CLI_CPF VARCHAR(14) NOT NULL UNIQUE,
	CLI_TELEFONE VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS VEICULOS(
	VEI_ID INT AUTO_INCREMENT PRIMARY KEY,
    VEI_PLACA VARCHAR(10) NOT NULL UNIQUE,
    VEI_MARCA VARCHAR(50) NOT NULL,
    VEI_MODELO VARCHAR(100) NOT NULL,
    VEI_ANO INT NOT NULL,
    FK_CLI_ID INT NOT NULL,
    FOREIGN KEY (FK_CLI_ID) REFERENCES CLIENTES(CLI_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS AGENDAMENTOS(
	AGE_ID INT AUTO_INCREMENT PRIMARY KEY,
    AGE_DATA_HORA DATETIME NOT NULL,
    AGE_SERVICO VARCHAR(100) NOT NULL,
    AGE_STATUS VARCHAR(30) NOT NULL,
    FK_CLI_ID INT NOT NULL,
    FK_VEI_ID INT NOT NULL,
    FOREIGN KEY (FK_CLI_ID) REFERENCES CLIENTES(CLI_ID) ON DELETE CASCADE,
    FOREIGN KEY (FK_VEI_ID) REFERENCES VEICULOS(VEI_ID) ON DELETE CASCADE
);

